data class SubscriptionFetchResult(
    val body: String,
    val finalUri: URI,
    val contentType: String?,
    val usage: SubscriptionUsage? = null,
    val updateIntervalHours: Int? = null,
) {
    val remoteMetadata get() = SubscriptionRemoteMetadata(usage, updateIntervalHours)
}

/**
 * Request expanded Walless nodes without forcing the legacy CFA response format. Provider
 * manifests are resolved by ClashProviderResolver, just as CMFA loads their node collections.
 * Only the exact legacy query generated by Weave is migrated; custom/signed queries are retained.
 */
internal object SubscriptionRequestCompatibility {
    // Walless has used several service domains over its lifetime. Keep this allowlist narrow so
    // ordinary subscriptions are never rewritten, while a redirect to an older/newer Walless
    // host keeps the documented expanded-node request.
    private val WALLLESS_ROOTS = setOf(
        "wallesspku.space",
        "wallesspku.org",
        "wallesspku.com",
        "wallesspku.net",
        "walless.top",
        "941321.xyz",
    )

    fun adapt(uri: URI): URI {
        val host = uri.host?.lowercase()?.trimEnd('.') ?: return uri
        if (WALLLESS_ROOTS.none { host == it || host.endsWith(".$it") }) return uri

        val components = uri.rawQuery.orEmpty().split('&').filter(String::isNotEmpty)
        val legacy = components.toSet() == setOf("client=cfa", "provider=false", "cluster=false") ||
            components.toSet() == setOf("client=cfa", "provider=false")
        val kept = if (legacy) components.filterNot { it == "client=cfa" || it == "provider=false" } else components
        val present = kept.joinToString("&")
            .split('&')
            .asSequence()
            .mapNotNull { component ->
                component.substringBefore('=', missingDelimiterValue = component)
                    .takeIf(String::isNotEmpty)
                    ?.lowercase()
            }
            .toSet()
        val additions = buildList {
            // Walless aggregates several physical servers into one advertised node by default.
            // Request its documented expanded view; never override an explicit user choice.
            if ("cluster" !in present) add("cluster=false")
        }
        if (additions.isEmpty() && !legacy) return uri

        // Do not append after a fragment. URI fragments are rejected by the normal URL policy,
        // but keeping this helper structurally correct also protects callers that use it before
        // validation (and avoids accidentally moving an anchor into the query string).
        val base = uri.toString().substringBefore('#').substringBefore('?')
        val fragment = uri.rawFragment?.let { "#$it" }.orEmpty()
        return URI(base + "?" + (kept + additions).joinToString("&") + fragment)
    }
}

/**
 * Small HTTPS-only fetcher with bounded redirects and response size.
 *
 * Redirects are handled manually so every hop is revalidated and an HTTPS subscription can never
 * silently downgrade to cleartext or pivot to a loopback/private literal.
 */
class SafeSubscriptionFetcher(
    private val urlPolicy: SubscriptionUrlPolicy = SubscriptionUrlPolicy(),
    private val maxBytes: Int = DEFAULT_MAX_BYTES,
    private val maxRedirects: Int = DEFAULT_MAX_REDIRECTS,
    resolver: (String) -> Array<InetAddress> = InetAddress::getAllByName,
    client: OkHttpClient = OkHttpClient(),
) {
    private val http = client.newBuilder()
        .proxy(Proxy.NO_PROXY)
        .followRedirects(false)
        .followSslRedirects(false)
        .connectTimeout(CONNECT_TIMEOUT_MS.toLong(), TimeUnit.MILLISECONDS)
        .readTimeout(READ_TIMEOUT_MS.toLong(), TimeUnit.MILLISECONDS)
        .dns(object : Dns {
            override fun lookup(hostname: String): List<InetAddress> = try {
                urlPolicy.validateResolvedAddresses(URI("https", null, hostname, -1, null, null, null), resolver).toList()
            } catch (error: SubscriptionImportException) {
                // OkHttp's asynchronous dispatcher requires DNS failures to be IOExceptions.
                throw UnknownHostException("Subscription DNS answer rejected").apply { initCause(error) }
            }
        })
        .build()

    suspend fun fetch(rawUrl: String, adaptMainSubscription: Boolean = true): SubscriptionFetchResult {
        var current = urlPolicy.validate(rawUrl)
        val deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(60)

        repeat(maxRedirects + 1) { hop ->
            currentCoroutineContext().ensureActive()
            // Apply this before every hop so a Walless redirect remains in expanded-node mode while
            // unrelated hosts and explicitly supplied parameters stay untouched.
            // Provider URLs already identify a concrete node file. Main-subscription query
            // compatibility flags must never be appended to a provider request.
            val compatible = if (adaptMainSubscription) SubscriptionRequestCompatibility.adapt(current) else current
            if (compatible != current) {
                current = urlPolicy.validate(compatible.toString())
            }
            // Honor the process route, including an already-working VPN. Binding exclusively
            // to physical networks made protected/blocked provider downloads fail and bypassed
            // the user's selected tunnel. Never silently bypass another VPN during import.
            val remainingMillis = TimeUnit.NANOSECONDS.toMillis(deadline - System.nanoTime())
            if (remainingMillis <= 0) throw SubscriptionImportException("订阅下载超时")
            val response = fetchHop(current, remainingMillis)
            when (response.status) {
                HttpURLConnection.HTTP_OK -> {
                    return SubscriptionFetchResult(
                        body = requireNotNull(response.body),
                        finalUri = current,
                        contentType = response.contentType,
                        usage = SubscriptionUsage.parse(response.userInfo),
                        updateIntervalHours = ProfileUpdateInterval.parse(response.updateInterval),
                    )
                }

                HttpURLConnection.HTTP_MOVED_PERM,
                HttpURLConnection.HTTP_MOVED_TEMP,
                HttpURLConnection.HTTP_SEE_OTHER,
                307,
                308,
                -> {
                    if (hop == maxRedirects) {
                        throw SubscriptionImportException("订阅重定向次数过多")
                    }
                    val location = response.location
                        ?: throw SubscriptionImportException("订阅重定向缺少目标地址")
                    current = urlPolicy.validate(current.resolve(location).toString())
                }

                else -> throw SubscriptionImportException("订阅服务器返回 HTTP ${response.status}")
            }
        }

        throw SubscriptionImportException("订阅重定向次数过多")
    }

    private data class HopResponse(
        val status: Int,
        val body: String? = null,
        val contentType: String? = null,
        val location: String? = null,
        val userInfo: String? = null,
        val updateInterval: String? = null,
    )

    private suspend fun fetchHop(uri: URI, remainingMillis: Long): HopResponse = try {
        executeHop(uri, remainingMillis)
    } catch (error: SocketTimeoutException) {
        throw SubscriptionImportException("订阅服务器连接超时，请检查当前网络或暂时关闭其他 VPN 后重试", error)
    } catch (error: IOException) {
        (error.cause as? SubscriptionImportException)?.let { throw it }
        throw SubscriptionImportException("无法连接订阅服务器，请检查当前网络或暂时关闭其他 VPN 后重试", error)
    }

    private suspend fun executeHop(uri: URI, remainingMillis: Long): HopResponse = suspendCancellableCoroutine { continuation ->
        val request = Request.Builder().url(uri.toString())
            .header("Accept", "application/yaml, text/yaml, text/plain, application/json, */*")
            .header("Accept-Encoding", "identity")
            .header("User-Agent", SubscriptionClientIdentity.USER_AGENT)
            .header("Cache-Control", "no-cache, no-transform")
            .build()
        val call = http.newCall(request)
        call.timeout().timeout(remainingMillis, TimeUnit.MILLISECONDS)
        continuation.invokeOnCancellation { call.cancel() }
        if (!continuation.isActive) return@suspendCancellableCoroutine
        call.enqueue(object : Callback {
            override fun onFailure(call: Call, e: IOException) {
                continuation.resumeWithException(e)
            }

            override fun onResponse(call: Call, response: Response) {
                try {
                    val result = response.use {
                        if (!continuation.isActive) return
                        readHop(it)
                    }
                    continuation.resume(result)
                } catch (error: Exception) {
                    continuation.resumeWithException(error)
                }
            }
        })
    }

    private fun readHop(response: Response): HopResponse =
        when (val status = response.code) {
            HttpURLConnection.HTTP_OK -> {
                val declared = response.body.contentLength()
                if (declared > maxBytes) {
                    throw SubscriptionImportException("订阅内容超过 ${maxBytes / 1024} KiB 限制")
                }
                val body = response.body.byteStream().use {
                    SubscriptionResponseBody.read(it, response.header("Content-Encoding"), maxBytes)
                }
                HopResponse(
                    status = status,
                    body = body,
                    contentType = response.header("Content-Type"),
                    userInfo = response.header("subscription-userinfo"),
                    updateInterval = response.header("profile-update-interval"),
                )
            }

            HttpURLConnection.HTTP_MOVED_PERM,
            HttpURLConnection.HTTP_MOVED_TEMP,
            HttpURLConnection.HTTP_SEE_OTHER,
            307,
            308,
            -> HopResponse(
                status = status,
                location = response.header("Location"),
            )

            else -> throw SubscriptionImportException("订阅服务器返回 HTTP $status")
        }

    private companion object {
        const val DEFAULT_MAX_BYTES = 5 * 1024 * 1024
        const val DEFAULT_MAX_REDIRECTS = 3
        const val CONNECT_TIMEOUT_MS = 10_000
        const val READ_TIMEOUT_MS = 15_000
    }
}
